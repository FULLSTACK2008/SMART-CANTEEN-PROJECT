export function translate(locale, text, values) {
  const dictionary = locale === 'rw' ? rw : locale === 'fr' ? fr : null
  const translated = dictionary?.[text] || text
  if (!values) return translated

  return translated.replace(/\{(\w+)\}/g, (placeholder, key) => (
    Object.hasOwn(values, key) ? values[key] : placeholder
  ))
}